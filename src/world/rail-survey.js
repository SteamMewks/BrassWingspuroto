function railSample(line,d){
 const pts=line.path;d=Math.max(0,Math.min(line.length,d));
 let lo=0,hi=pts.length-1;
 while(hi-lo>1){const m=(lo+hi)>>1;if(pts[m].d<=d)lo=m;else hi=m}
 const a=pts[lo],b=pts[hi],l=b.d-a.d,u=(d-a.d)/l;
 return {x:a.x+(b.x-a.x)*u,z:a.z+(b.z-a.z)*u,y:a.y+(b.y-a.y)*u,dx:(b.x-a.x)/l,dz:(b.z-a.z)/l}
}
